package main

import (
	"flag"
	"fmt"
	"io"
	"os"
	"sort"
	"strings"
)

// cmdLedger renders COMPATIBILITY.md from the manifest. The manifest is the
// source of truth; CI fails if the rendered file is stale.
func cmdLedger(args []string) error {
	fs := flag.NewFlagSet("ledger", flag.ContinueOnError)
	manifestPath := fs.String("manifest", "", "ABI manifest")
	if err := fs.Parse(args); err != nil {
		return err
	}
	m, err := loadManifest(*manifestPath)
	if err != nil {
		return err
	}
	renderLedger(os.Stdout, m)
	return nil
}

func yesNo(b bool) string {
	if b {
		return "yes"
	}
	return "no"
}

func cell(s string) string {
	if s == "" {
		return "—"
	}
	return strings.ReplaceAll(s, "|", "\\|")
}

func renderLedger(w io.Writer, m *Manifest) {
	fmt.Fprintf(w, "# Compatibility ledger\n\n")
	fmt.Fprintf(w, "<!-- Generated by `make ledger` from %s. Do not edit by hand. -->\n\n", "abi/vddk-8.0.3/manifest.json")
	fmt.Fprintf(w, "Claimed generation: **%s**. Reference: `%s` (`%s`, SHA-256 `%s`).\n\n",
		m.Generation, m.Reference.Package, m.Reference.Library, m.Reference.LibrarySHA256)
	fmt.Fprintf(w, "This library is not a complete VixDiskLib replacement. Only rows marked SUPPORTED are claimed; "+
		"every other entry point fails explicitly with the error shown in its notes. "+
		"Artifact: `%s` (SONAME `%s`), glibc floor GLIBC_%s.\n\n", m.Soname, m.Soname, m.MaxGlibc)

	counts := map[string]int{}
	for _, f := range m.Functions {
		counts[f.Status]++
	}
	statuses := make([]string, 0, len(counts))
	for s := range counts {
		statuses = append(statuses, s)
	}
	sort.Strings(statuses)
	fmt.Fprintf(w, "## Summary\n\n| Status | Functions |\n|---|---|\n")
	for _, s := range statuses {
		fmt.Fprintf(w, "| %s | %d |\n", s, counts[s])
	}
	fmt.Fprintf(w, "\nStatus meanings:\n\n")
	for _, s := range m.StatusLegend {
		fmt.Fprintf(w, "- %s\n", s)
	}

	fmt.Fprintf(w, "\n## Functions\n\n")
	fmt.Fprintf(w, "| Function | Version node | Exported | Semantics | Managed disk | Hosted disk | Thread safety | Differential tests | Application uses | Application exercised | External consumer | Status |\n")
	fmt.Fprintf(w, "|---|---|---|---|---|---|---|---|---|---|---|---|\n")
	for _, f := range m.Functions {
		tests := "—"
		if len(f.Differential) > 0 {
			tests = "`" + strings.Join(f.Differential, "`, `") + "`"
		}
		fmt.Fprintf(w, "| `%s` | %s | %s | %s | %s | %s | %s | %s | %s | %s | %s | **%s** |\n",
			f.Name, f.Version, yesNo(f.Exported), cell(f.Semantics), cell(f.Managed), cell(f.Hosted),
			cell(f.ThreadSafety), tests, cell(f.AppUses), yesNo(f.AppTested), cell(f.External), f.Status)
	}

	fmt.Fprintf(w, "\n## Notes and known differences\n\n")
	for _, f := range m.Functions {
		if f.Differences == "" && f.Ownership == "" {
			continue
		}
		fmt.Fprintf(w, "### `%s`\n\n`%s`\n\n", f.Name, f.Signature)
		if f.Ownership != "" {
			fmt.Fprintf(w, "- Ownership: %s\n", f.Ownership)
		}
		if f.Differences != "" {
			fmt.Fprintf(w, "- Known differences: %s\n", f.Differences)
		}
		fmt.Fprintln(w)
	}
}
