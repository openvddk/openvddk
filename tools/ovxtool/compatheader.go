package main

import (
	"flag"
	"fmt"
	"io"
	"os"
	"regexp"
	"sort"

	"github.com/openvddk/openvddk/internal/vix"
)

// cmdCompatHeader renders include/vixDiskLib.h, the source-compatibility
// header (D-0038). Its error codes come from the library's own table, so the
// header and GetErrorText cannot disagree; names the ABI header already
// defines are left out. CI fails if the committed file is stale.
func cmdCompatHeader(args []string) error {
	fs := flag.NewFlagSet("compat-header", flag.ContinueOnError)
	abiPath := fs.String("abi", "include/openvix/vixdisklib_abi.h", "the ABI header")
	if err := fs.Parse(args); err != nil {
		return err
	}
	abi, err := os.ReadFile(*abiPath)
	if err != nil {
		return err
	}
	renderCompatHeader(os.Stdout, definedNames(abi))
	return nil
}

// definedNames returns the macro and enumerator names a header defines.
func definedNames(src []byte) map[string]bool {
	names := map[string]bool{}
	for _, re := range []*regexp.Regexp{
		regexp.MustCompile(`(?m)^\s*#\s*define\s+([A-Za-z_][A-Za-z0-9_]*)`),
		regexp.MustCompile(`(?m)^\s*([A-Z][A-Z0-9_]*)\s*=`),
	} {
		for _, m := range re.FindAllSubmatch(src, -1) {
			names[string(m[1])] = true
		}
	}
	return names
}

// hwVersions are the virtual hardware versions for
// VixDiskLibCreateParams.hwVersion, as the generation-8 declarations number
// them.
var hwVersions = []struct {
	name  string
	value string
}{
	{"VIXDISKLIB_HWVERSION_WORKSTATION_4", "3"},
	{"VIXDISKLIB_HWVERSION_WORKSTATION_5", "4"},
	{"VIXDISKLIB_HWVERSION_WORKSTATION_6", "6"},
	{"VIXDISKLIB_HWVERSION_ESX30", "VIXDISKLIB_HWVERSION_WORKSTATION_5"},
	{"VIXDISKLIB_HWVERSION_ESX4X", "7"},
	{"VIXDISKLIB_HWVERSION_ESX50", "8"},
	{"VIXDISKLIB_HWVERSION_ESX51", "9"},
	{"VIXDISKLIB_HWVERSION_ESX55", "10"},
	{"VIXDISKLIB_HWVERSION_ESX60", "11"},
	{"VIXDISKLIB_HWVERSION_ESX65", "13"},
	{"VIXDISKLIB_HWVERSION_CURRENT", "VIXDISKLIB_HWVERSION_ESX65"},
}

func renderCompatHeader(w io.Writer, inABI map[string]bool) {
	fmt.Fprint(w, `/*
 * Copyright 2026 Andrija Panic and the OpenVDDK contributors
 * SPDX-License-Identifier: Apache-2.0
 */

/*
 * vixDiskLib.h: source compatibility for programs written against the
 * VixDiskLib C API, generation 8.
 *
 * Such programs include "vixDiskLib.h", compare results with the VIX_E_*
 * codes and test them with VIX_SUCCEEDED and VIX_FAILED. This file adds
 * those names to the ABI declarations in openvix/vixdisklib_abi.h, so the
 * programs build against OpenVDDK without any other header.
 *
 * Generated by "ovxtool compat-header" from the library's error table
 * (internal/vix/codes.go); do not edit. Provenance: D-0005, D-0038.
 */
#ifndef OPENVIX_VIXDISKLIB_COMPAT_H
#define OPENVIX_VIXDISKLIB_COMPAT_H

#include "openvix/vixdisklib_abi.h"

/* The basic type names VixDiskLib programs use. Define
 * OPENVIX_NO_BASIC_TYPES when another header provides them already. */
#ifndef OPENVIX_NO_BASIC_TYPES
typedef VixDiskLibBool Bool;
typedef uint8_t  uint8;
typedef uint16_t uint16;
typedef uint32_t uint32;
typedef uint64_t uint64;
#ifndef TRUE
#define TRUE  1
#endif
#ifndef FALSE
#define FALSE 0
#endif
#endif

#define VIX_SUCCEEDED(err) ((err) == VIX_OK)
#define VIX_FAILED(err)    ((err) != VIX_OK)

/* Virtual hardware versions (VixDiskLibCreateParams.hwVersion). */
enum {
`)
	for i, h := range hwVersions {
		sep := ","
		if i == len(hwVersions)-1 {
			sep = ""
		}
		fmt.Fprintf(w, "   %-36s = %s%s\n", h.name, h.value, sep)
	}
	fmt.Fprint(w, `};

/* Error codes: the low 16 bits of a VixError (see VIX_ERROR_CODE). */
`)
	codes := vix.Codes()
	sort.Slice(codes, func(i, j int) bool { return codes[i] < codes[j] })
	for _, c := range codes {
		name := c.Name()
		if name == "" || inABI[name] {
			continue
		}
		fmt.Fprintf(w, "#define %-48s ((VixError)%d)\n", name, int(c))
	}
	fmt.Fprint(w, `
#endif /* OPENVIX_VIXDISKLIB_COMPAT_H */
`)
}
